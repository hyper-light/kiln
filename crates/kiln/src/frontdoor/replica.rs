    fn server_pipeline_link(offline: bool) -> anyhow::Result<()> {
        let dir = tempfile::tempdir()?;
        let machine = crate::util::new_id();
        let key = crate::util::random_token();
        let token = dir.path().join("session-admin.token");
        std::fs::write(&token, &key)?;
        let (link, network) = crate::reach::node::start(crate::reach::node::Config {
            sense: false,
            direct_quic: false,
            ..crate::reach::node::Config::for_runner(&machine, dir.path(), true)
        })?;
        let responder = link.clone();
        let (submitted, heard) = async_channel::bounded(1);
        crate::rt::block_on(async move {
            if !offline {
                anyhow::ensure!(responder.feed(crate::reach::node::In::Server(true)).await);
            }
            crate::rt::spawn(async move {
                while let Ok(frame) = network.recv().await {
                    if let crate::proto::AgentMsg::ReachAsk { req, json } = frame
                        && let Ok(crate::reach::Question::SessionPlacement { key, body, agents: false, .. }) = serde_json::from_str(&json)
                    {
                        let confirmation = json!([{"id":body.pointer("/ids/0"),"target":"agent:placed","server_placed":true}]);
                        responder
                            .feed(crate::reach::node::In::Answer {
                                req,
                                answer: json!({"status":200,"answer":confirmation}),
                            })
                            .await;
                        let _ = submitted.send((key, body)).await;
                        break;
                    }
                }
            });
            Ok(())
        })?;
        let origin = LocalNode {
            max_children:Some(24),
            machine,
            reach: Some(link.clone()),
            owner_key_file: Some(token),
            node_admin_key: true,
            ..Default::default()
        };
        let unavailable = std::net::TcpListener::bind("127.0.0.1:0")?.local_addr()?;
        let door = serve(Arc::new(Door::for_node(Upstream::parse(&format!("http://{unavailable}"), &[])?, origin)?))?;
        let headers = format!("authorization: Bearer {key}\r\nIdempotency-Key: choose-for-me\r\n");
        let id = crate::util::derive_id(&["fleet-start-v1", "choose-for-me", "0"]);
        let (code, _, body) = send_http(door, "/api/harness/sessions", &headers, r#"{"spec":{"kind":"codex"}}"#)?;
        let value: serde_json::Value = serde_json::from_str(&body)?;
        if offline {
            anyhow::ensure!(
                code == 202 && value.pointer("/0/outcome") == Some(&json!("held")) && value.pointer("/0/target") == Some(&json!("server")),
                "{code}: {body}"
            );
            anyhow::ensure!(heard.try_recv().is_err());
        } else {
            anyhow::ensure!(
                code == 200 && value.pointer("/0/server_placed") == Some(&json!(true)) && value.pointer("/0/id") == Some(&json!(id)),
                "{code}: {body}"
            );
        }
        crate::rt::block_on(async move {
            if offline {
                anyhow::ensure!(link.feed(crate::reach::node::In::Server(true)).await);
            }
            let (key, body) = crate::rt::timeout(crate::hub::COMMAND_WITHIN, heard.recv()).await??;
            anyhow::ensure!(key == "choose-for-me" && body.pointer("/ids/0") == Some(&json!(id)) && body.get("target").is_none());
            if offline {
                crate::rt::timeout(crate::hub::COMMAND_WITHIN, async {
                    loop {
                        if link.starts.visible(key.clone()).await?.first().and_then(|s| s.get("outcome")) == Some(&json!("forwarded")) {
                            return anyhow::Ok(());
                        }
                        hyper_rt::futures::yield_now().await;
                    }
                })
                .await??;
            }
            Ok(())
        })
    }
