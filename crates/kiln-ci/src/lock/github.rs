//! GitHub's actions.lock (W29-R23): bounded, positioned reading and deterministic writing.
//! Compatibility follows github/actions-lockfile go/v0.0.6 (ac1588347652) and the serializer
//! in github/gh-actions-lock at 113f91d77e0a. The latter writes direct roots plus uses edges.
//! Source identity and git provenance are verified separately, before anything executes.

use std::collections::{BTreeMap, BTreeSet};

use serde::{Deserialize, Serialize};

use crate::wf::diag::{Diag, Pos, Range};
use crate::wf::yaml::{self, Node, Scalar};

pub const PATH: &str = ".github/workflows/actions.lock";
pub const VERSION: &str = "v0.0.3";
pub const HEADER: &str = "# This file is machine-generated by \x60gh actions-lock\x60.\n# Do not edit by hand; run \x60gh actions-lock\x60 to update.\n# Docs: https://gh.io/actions-lockfile\n";

/// One repository and ref. Sub-action directories do not distinguish the downloaded tree.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct Action {
    pub hostname: Option<String>,
    #[serde(rename = "ref")]
    pub git_ref: String,
    pub commit: String,
    pub owner_id: i64,
    pub repo_id: i64,
    pub uses: Vec<String>,
}

/// Normalized v0.0.3 data. Missing workflow and onboarded-with-no-actions are distinct.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct File {
    pub version: String,
    pub workflows: BTreeMap<String, Vec<String>>,
    pub dependencies: BTreeMap<String, Action>,
}

impl Default for File {
    fn default() -> Self {
        Self { version: VERSION.into(), workflows: BTreeMap::new(), dependencies: BTreeMap::new() }
    }
}

type Read<T> = Result<T, Box<Diag>>;

fn error(node: Option<&Node>, message: impl Into<String>) -> Box<Diag> {
    let range = node.map_or(Range { start: Pos { line: 1, col: 1, offset: 0 }, end: Pos { line: 1, col: 1, offset: 0 } }, |n| n.range);
    Box::new(Diag::error("KCI1022", message, range).at(PATH))
}

fn string(node: &Node) -> Option<&str> {
    match node.as_scalar() { Some(Scalar::Str(s)) => Some(s), _ => None }
}

fn required<'a>(node: &'a Node, key: &str) -> Read<&'a Node> {
    node.get(key).ok_or_else(|| error(Some(node), format!("missing required lock field {key:?}")))
}

fn text(node: &Node) -> Read<String> {
    string(node).map(str::to_owned).ok_or_else(|| error(Some(node), format!("expected a string, found {}", node.type_name())))
}

struct Source<'a> {
    text: &'a str,
    // yaml-rust2's scanner indexes characters. Scalar primitives are ASCII, but their
    // preceding comments and keys need not be. Build this translation once, not per field.
    bytes: Option<Vec<usize>>,
}

impl<'a> Source<'a> {
    fn new(text: &'a str) -> Self {
        let bytes = if text.is_ascii() { None } else {
            let mut bytes: Vec<_> = text.char_indices().map(|(at, _)| at).collect();
            bytes.push(text.len());
            Some(bytes)
        };
        Self { text, bytes }
    }

    fn raw(&self, node: &Node) -> Option<&'a str> {
        let position = |n| {
            let n = usize::try_from(n).ok()?;
            match &self.bytes { Some(bytes) => bytes.get(n).copied(), None => Some(n) }
        };
        let (from, to) = (position(node.range.start.offset)?, position(node.range.end.offset)?);
        if to > from { self.text.get(from..to) } else { None }
    }
}

/// yaml.v3 decodes primitive scalars into Go string fields using their original spelling.
/// In particular, a tag named 1.0 must not become the ref 1 through numeric normalization.
fn scalar_text(source: &Source<'_>, node: &Node) -> Read<String> {
    match node.as_scalar() {
        Some(Scalar::Str(s)) => Ok(s.clone()),
        Some(Scalar::Bool(_) | Scalar::Int(_) | Scalar::Float(_)) => Ok(source.raw(node).map(str::to_owned).or_else(|| node.text()).unwrap_or_default()),
        _ => Err(error(Some(node), "expected a scalar string value")),
    }
}

fn mapping(node: &Node) -> Read<&[(Node, Node)]> {
    node.as_map().ok_or_else(|| error(Some(node), format!("expected a mapping, found {}", node.type_name())))
}

fn fields(node: &Node, allowed: &[&str]) -> Read<()> {
    for (key, _) in mapping(node)? {
        if !string(key).is_some_and(|s| allowed.contains(&s)) {
            return Err(error(Some(key), format!("unknown lock field {:?}", key.text().unwrap_or_default())));
        }
    }
    Ok(())
}

/// A SHA-1 or SHA-256 in the algorithm-prefixed lockfile form.
pub fn digest(value: &str) -> Option<&str> {
    let (algorithm, hex) = value.split_once('-')?;
    let length = match algorithm { "sha1" => 40, "sha256" => 64, _ => return None };
    (hex.len() == length && hex.bytes().all(|b| b.is_ascii_hexdigit())).then_some(hex)
}

fn full_sha(value: &str) -> bool {
    matches!(value.len(), 40 | 64) && value.bytes().all(|b| b.is_ascii_hexdigit())
}

fn legacy_suffix(value: &str) -> Option<&str> {
    let (git_ref, suffix) = value.rsplit_once(':')?;
    let (algorithm, hex) = suffix.split_once('-')?;
    (matches!(algorithm, "sha1" | "sha256") && !hex.is_empty() && hex.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))).then_some(git_ref)
}

fn pin(value: &str, legacy: bool) -> Option<String> {
    let (repo, value) = value.split_once('@')?;
    let git_ref = if legacy { legacy_suffix(value).unwrap_or(value) } else { value };
    let (owner, name) = repo.split_once('/')?;
    if owner.is_empty() || name.is_empty() || name.contains('/') || git_ref.is_empty() || git_ref.contains(':') {
        return None;
    }
    Some(format!("{}/{}@{git_ref}", owner.to_lowercase(), name.to_lowercase()))
}

/// A serialized repository/ref key, preserving ref case.
pub fn canonical_pin(value: &str) -> Option<String> {
    pin(value, false)
}

/// A step's uses value as its repository/ref key. Local, image and reusable references have
/// different lock ownership and are not action pins.
pub fn action_pin(value: &str) -> Option<String> {
    let value = value.trim();
    if ["./", "$/", "docker://", "kiln://", "kiln/"].iter().any(|p| value.starts_with(*p)) || value.contains(concat!("$", "{")) {
        return None;
    }
    let (path, git_ref) = value.trim().split_once('@')?;
    let mut segments = path.splitn(3, '/');
    let (owner, repo) = (segments.next()?, segments.next()?);
    let sub = segments.next();
    if sub.is_some_and(|s| s.starts_with(".github/workflows/") && (s.ends_with(".yml") || s.ends_with(".yaml"))) {
        return None;
    }
    let safe = |s: &str| !s.is_empty() && s != "." && s != ".." && s.chars().all(|c| c.is_ascii_alphanumeric() || "-_.".contains(c));
    if !safe(owner) || !safe(repo) || sub.is_some_and(|p| p.split('/').any(|s| !safe(s))) {
        return None;
    }
    canonical_pin(&format!("{owner}/{repo}@{git_ref}"))
}

fn pins(node: &Node, legacy: bool) -> Read<Vec<String>> {
    if node.is_null() { return Ok(Vec::new()); }
    let items = node.as_seq().ok_or_else(|| error(Some(node), "expected a list of lock pins"))?;
    items.iter().map(|n| pin(&text(n)?, legacy).ok_or_else(|| error(Some(n), "a lock pin is owner/repo@ref, without an action's subdirectory"))).collect()
}

fn positive(source: &Source<'_>, node: &Node) -> Read<i64> {
    if matches!(node.as_scalar(), Some(Scalar::Int(_))) {
        let value = source.raw(node).map(str::to_owned).or_else(|| node.text()).unwrap_or_default();
        let digits = value.strip_prefix('+').unwrap_or(&value);
        if !digits.is_empty() && digits.bytes().all(|b| b.is_ascii_digit()) && value.parse::<i64>().is_ok_and(|n| n > 0) {
            // Go's decoder retains YAML 1.1 octal while its required-field validator
            // separately requires a positive base-10 spelling (so 0x1 is rejected).
            let decoded = if digits.len() > 1 && digits.starts_with('0') && digits.bytes().all(|b| (b'0'..=b'7').contains(&b)) {
                i64::from_str_radix(digits, 8).ok()
            } else { value.parse::<i64>().ok() };
            if let Some(n) = decoded.filter(|n| *n > 0) { return Ok(n); }
        }
    }
    Err(error(Some(node), "a repository or owner ID must be a positive integer"))
}

fn hostname(value: &str) -> bool {
    if value == "github.com" { return true; }
    let Some(tenant) = value.strip_suffix(".ghe.com") else { return false };
    let alnum = |b: u8| b.is_ascii_lowercase() || b.is_ascii_digit();
    !tenant.is_empty() && tenant.len() <= 63 && tenant.bytes().next().is_some_and(alnum) && tenant.bytes().last().is_some_and(alnum) && tenant.bytes().all(|b| alnum(b) || b == b'-')
}

fn workflow_path(value: &str) -> bool {
    !value.is_empty() && !value.starts_with('/') && !value.chars().any(|c| c <= '\x1f' || c == '\x7f' || c == '\\' || c == ':') && !value.split('/').any(|s| s == "..")
}

fn action(source: &Source<'_>, key: &str, node: &Node, version: &str) -> Read<Action> {
    let legacy = version == "v0.0.1";
    let allowed: &[&str] = match version {
        "v0.0.1" => &["tag", "branch", "commit", "owner_id", "repo_id", "uses"],
        "v0.0.2" => &["ref", "commit", "owner_id", "repo_id", "uses"],
        _ => &["hostname", "ref", "commit", "owner_id", "repo_id", "uses"],
    };
    fields(node, allowed)?;
    let key_ref = key.split_once('@').map(|(_, r)| r).unwrap_or_default();
    let git_ref = if legacy {
        let old_ref = |n: &Node| if n.is_null() { Ok(String::new()) } else { scalar_text(source, n) };
        let tag = node.get("tag").map(old_ref).transpose()?.unwrap_or_default();
        let branch = node.get("branch").map(old_ref).transpose()?.unwrap_or_default();
        if !tag.is_empty() { tag } else if !branch.is_empty() { branch } else { key_ref.to_owned() }
    } else { scalar_text(source, required(node, "ref")?)? };
    let commit_node = required(node, "commit")?;
    let commit = text(commit_node)?;
    let Some(hex) = digest(&commit) else { return Err(error(Some(commit_node), "a locked commit must be sha1-<40 hex digits> or sha256-<64 hex digits>")) };
    if git_ref.is_empty() { return Err(error(node.get("ref"), "a locked ref must not be empty")); }
    if !legacy && !full_sha(key_ref) && git_ref != key_ref {
        return Err(error(node.get("ref"), format!("body ref {git_ref:?} differs from pin ref {key_ref:?}")));
    }
    if !legacy && full_sha(key_ref) && !key_ref.eq_ignore_ascii_case(hex) {
        return Err(error(Some(commit_node), "a full-SHA pin must match its locked commit"));
    }
    let host = node.get("hostname").map(text).transpose()?;
    if let Some(host) = &host && !hostname(host) {
        return Err(error(node.get("hostname"), "hostname must be github.com or a lowercase tenant.ghe.com hostname"));
    }
    Ok(Action {
        hostname: if version == VERSION { host } else { Some("github.com".into()) },
        git_ref, commit,
        owner_id: positive(source, required(node, "owner_id")?)?,
        repo_id: positive(source, required(node, "repo_id")?)?,
        uses: node.get("uses").map(|n| pins(n, legacy)).transpose()?.unwrap_or_default(),
    })
}

fn read(source: &Source<'_>, root: &Node) -> Read<File> {
    fields(root, &["version", "workflows", "dependencies"])?;
    let version_node = required(root, "version")?;
    let version = text(version_node)?;
    if !matches!(version.as_str(), "v0.0.1" | "v0.0.2" | VERSION) {
        return Err(error(Some(version_node), format!("unsupported lock version {version:?}; supported versions are v0.0.1 to {VERSION}; upgrade before reading a newer format")));
    }
    let legacy = version == "v0.0.1";
    let mut file = File::default();
    if let Some(workflows) = root.get("workflows").filter(|n| !n.is_null()) {
        for (key, value) in mapping(workflows)? {
            let path = scalar_text(source, key)?;
            if !workflow_path(&path) { return Err(error(Some(key), "a workflow key must be a safe repository-relative path")); }
            file.workflows.insert(path, pins(value, legacy)?);
        }
    }
    let mut ranges = BTreeMap::new();
    if let Some(deps) = root.get("dependencies").filter(|n| !n.is_null()) {
        for (key, value) in mapping(deps)? {
            let Some(name) = pin(&text(key)?, legacy) else { return Err(error(Some(key), "a dependency key must be owner/repo@ref")) };
            let a = action(source, &name, value, &version)?;
            if let Some(old) = file.dependencies.get(&name) && old != &a {
                return Err(error(Some(key), format!("conflicting metadata for canonical pin {name:?}")));
            }
            ranges.insert(name.clone(), key);
            file.dependencies.insert(name, a);
        }
    }
    if let Some(key) = cycle(&file.dependencies) {
        return Err(error(ranges.get(&key).copied(), format!("dependency uses graph has a cycle at {key:?}")));
    }
    Ok(file)
}

/// W29-R23: structural errors fail closed and retain their source position. No source access.
pub fn parse(source: &str) -> Result<File, Vec<Diag>> {
    let mut diagnostics = Vec::new();
    let root = yaml::parse(source, &mut diagnostics);
    if diagnostics.iter().any(Diag::is_error) {
        return Err(diagnostics.into_iter().filter(Diag::is_error).map(|mut d| { d.code = "KCI1022"; d.path = PATH.into(); d }).collect());
    }
    root.ok_or_else(|| vec![*error(None, "a lockfile needs a version and a mapping")]).and_then(|root| read(&Source::new(source), &root).map_err(|d| vec![*d]))
}

fn cycle(dependencies: &BTreeMap<String, Action>) -> Option<String> {
    let (mut active, mut done) = (BTreeSet::new(), BTreeSet::new());
    for root in dependencies.keys() {
        let mut todo = vec![(root.as_str(), false)];
        while let Some((key, leaving)) = todo.pop() {
            if leaving { active.remove(key); done.insert(key); continue; }
            if done.contains(key) { continue; }
            if !active.insert(key) { return Some(key.to_owned()); }
            todo.push((key, true));
            if let Some(a) = dependencies.get(key) { todo.extend(a.uses.iter().rev().map(|u| (u.as_str(), false))); }
        }
    }
    None
}

impl File {
    /// Every reachable pin, including a missing one for the verifier to report (KCI4050).
    pub fn closure(&self, workflow: &str) -> Option<Vec<String>> {
        let mut todo = self.workflows.get(workflow)?.clone();
        let mut seen = BTreeSet::new();
        while let Some(key) = todo.pop() {
            if seen.insert(key.clone()) && let Some(a) = self.dependencies.get(&key) { todo.extend(a.uses.iter().cloned()); }
        }
        Some(seen.into_iter().collect())
    }

    /// W29-R23: bytes of the pinned CLI serializer. The regenerator decides whether an empty
    /// file should be removed, and prunes orphan pins before writing, as the CLI's Save does.
    pub fn write(&self, home_host: &str) -> Result<String, Vec<Diag>> {
        let fail = |message| vec![*error(None, message)];
        if self.version != VERSION || !hostname(home_host) {
            return Err(fail("writing this format needs v0.0.3 and a GitHub Cloud home hostname"));
        }
        if self.workflows.keys().any(|p| !workflow_path(p)) || self.workflows.values().flatten().chain(self.dependencies.values().flat_map(|a| &a.uses)).any(|p| p.chars().any(char::is_control)) {
            return Err(fail("workflow paths and pins must be safe repository-relative source references"));
        }
        let quote = |s: &str| format!("'{}'", s.replace('\'', "''"));
        let list = |out: &mut String, values: &[String], indent: &str| {
            let mut values = values.to_vec();
            values.sort();
            for value in values { out.push_str(&format!("{indent}- {}\n", quote(&value))); }
        };
        let mut out = format!("{HEADER}version: '{}'\n", VERSION);
        if !self.workflows.is_empty() {
            out.push_str("workflows:\n");
            for (path, uses) in &self.workflows {
                out.push_str(&format!("    {}:{}", quote(path), if uses.is_empty() { " []\n" } else { "\n" }));
                list(&mut out, uses, "        ");
            }
        }
        if !self.dependencies.is_empty() { out.push_str("dependencies:\n"); }
        let mut hosts = BTreeMap::new();
        for (key, a) in &self.dependencies {
            let Some((repo, _)) = key.split_once('@') else { return Err(fail("a dependency key needs a ref")) };
            let host = a.hostname.as_deref().unwrap_or(home_host);
            if hosts.insert(repo, host).is_some_and(|old| old != host) {
                return Err(fail("one action repository cannot name two source hosts"));
            }
            if key.chars().any(char::is_control) || a.git_ref.chars().any(char::is_control) {
                return Err(fail("a source pin or git ref cannot contain control characters"));
            }
            out.push_str(&format!("    {}:\n", quote(key)));
            if host != home_host {
                if host != "github.com" { return Err(fail("a cross-host dependency must be bound to github.com")); }
                out.push_str(&format!("        hostname: {}\n", quote(host)));
            }
            out.push_str(&format!("        ref: {}\n        commit: {}\n        owner_id: {}\n        repo_id: {}\n", quote(&a.git_ref), quote(&a.commit), a.owner_id, a.repo_id));
            if !a.uses.is_empty() { out.push_str("        uses:\n"); list(&mut out, &a.uses, "            "); }
        }
        // Typed data can be built by callers too. Never emit invalid or over-limit lock data.
        parse(&out)?;
        Ok(out)
    }
}

